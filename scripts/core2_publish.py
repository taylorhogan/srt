"""Build the Core2 display's firmware and publish it for over-the-air update (2026-10-26).

    python scripts/core2_publish.py              # compile + publish; the Core2 updates itself
    python scripts/core2_publish.py --flash      # ...and also flash over USB (first install)
    webchat: core2 publish

The Core2 never listens for anything. It reads /api/dash every 30 s, sees
"fw": {"v", "size", "hmac"}, and when "v" differs from its own build it fetches
/api/dash?part=firmware -- the same path and method as its allowlist
exception -- writes it to the spare app slot while computing HMAC-SHA256 with
the shared key, and only boots it if the HMAC matches.

The key: 32 random bytes made on first use, kept in local/core2_fw/ota_key.bin
(server) and devices/core2_dash/ota_key.h (sketch); both gitignored and never
printed. Changing it means one more USB flash.

The build folder holds a copy of secrets.h compiled in (the Wi-Fi password),
so it is deleted as soon as the .bin is copied out.
"""
import argparse
import hashlib
import hmac
import json
import os
import secrets
import shutil
import subprocess
import sys
import tempfile
from datetime import datetime
from pathlib import Path

if __package__ is None or __package__ == "":
    _root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    if _root not in sys.path:
        sys.path.insert(0, _root)

ROOT = Path(__file__).resolve().parent.parent
SKETCH = ROOT / "devices" / "core2_dash"
FW_DIR = ROOT / "local" / "core2_fw"
KEY_BIN = FW_DIR / "ota_key.bin"
KEY_H = SKETCH / "ota_key.h"
VERSION_H = SKETCH / "fw_version.h"
MANIFEST = FW_DIR / "manifest.json"
FIRMWARE = FW_DIR / "firmware.bin"
FQBN = "m5stack:esp32:m5stack_core2"
CLI = Path(os.environ.get("USERPROFILE", "")) / "tools" / "arduino-cli" / "arduino-cli.exe"
CORE2_USB = "VID_1A86&PID_55D4"          # the Core2's CH9102; COM7 is a different ESP32


def ensure_key() -> bytes:
    """The shared OTA key: made once, then reused. Writes the sketch's header if missing."""
    FW_DIR.mkdir(parents=True, exist_ok=True)
    if not KEY_BIN.exists():
        KEY_BIN.write_bytes(secrets.token_bytes(32))
    key = KEY_BIN.read_bytes()
    body = ", ".join("0x%02x" % b for b in key)
    header = ("// Generated by scripts/core2_publish.py -- gitignored, never commit.\n"
              "#pragma once\nstatic const uint8_t OTA_KEY[32] = {%s};\n" % body)
    if not KEY_H.exists() or KEY_H.read_text() != header:
        KEY_H.write_text(header)
    return key


def firmware_hmac(key: bytes, data: bytes) -> str:
    """Hex HMAC-SHA256 of the firmware, as the Core2 computes it while downloading. Pure."""
    return hmac.new(key, data, hashlib.sha256).hexdigest()


def build_version() -> str:
    """git short hash + build time, e.g. 1a1429b-1026T0815; '+dirty' if the sketch has local edits."""
    try:
        h = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
                           capture_output=True, text=True, timeout=20).stdout.strip()
        dirty = subprocess.run(["git", "-C", str(ROOT), "status", "--porcelain", "--", str(SKETCH)],
                               capture_output=True, text=True, timeout=20).stdout.strip()
    except Exception:  # noqa: BLE001
        h, dirty = "nogit", ""
    return "%s%s-%s" % (h or "nogit", "+dirty" if dirty else "", datetime.now().strftime("%m%dT%H%M"))


def core2_port():
    """The COM port of the Core2 on USB, found by its USB id, or None."""
    try:
        out = subprocess.run(["powershell", "-NoProfile", "-Command",
                              "(Get-CimInstance Win32_PnPEntity | Where-Object { $_.DeviceID -match '%s' }).Name"
                              % CORE2_USB], capture_output=True, text=True, timeout=30).stdout
    except Exception:  # noqa: BLE001
        return None
    import re
    m = re.search(r"\((COM\d+)\)", out or "")
    return m.group(1) if m else None


def publish(flash: bool = False, log=print) -> dict:
    if not CLI.exists():
        raise RuntimeError("arduino-cli not found at %s" % CLI)
    if not (SKETCH / "secrets.h").exists():
        raise RuntimeError("devices/core2_dash/secrets.h is missing (Wi-Fi details)")
    key = ensure_key()
    version = build_version()
    VERSION_H.write_text("#pragma once\n#define FW_VERSION \"%s\"\n" % version)
    build = Path(tempfile.mkdtemp(prefix="core2_build_"))
    try:
        log("core2: compiling %s ..." % version)
        r = subprocess.run([str(CLI), "compile", "--fqbn", FQBN, "--build-path", str(build), str(SKETCH)],
                           capture_output=True, text=True, timeout=900)
        if r.returncode != 0:
            raise RuntimeError("compile failed:\n" + (r.stderr or r.stdout)[-1500:])
        binary = build / "core2_dash.ino.bin"
        data = binary.read_bytes()
        tmp = FIRMWARE.with_suffix(".tmp")
        tmp.write_bytes(data)
        os.replace(tmp, FIRMWARE)
        manifest = {"v": version, "size": len(data), "hmac": firmware_hmac(key, data),
                    "built": datetime.now().isoformat(timespec="seconds")}
        MANIFEST.write_text(json.dumps(manifest, indent=1))
        log("core2: published %s (%d bytes); the Core2 picks it up within a few minutes" % (version, len(data)))
        if flash:
            port = core2_port()
            if not port:
                raise RuntimeError("the Core2 is not on USB (looked for %s)" % CORE2_USB)
            log("core2: flashing over USB on %s ..." % port)
            u = subprocess.run([str(CLI), "upload", "-p", port, "--fqbn", FQBN, "--input-dir", str(build)],
                               capture_output=True, text=True, timeout=600)
            if u.returncode != 0:
                raise RuntimeError("USB upload failed:\n" + (u.stderr or u.stdout)[-1500:])
            log("core2: flashed over USB")
        return manifest
    finally:
        shutil.rmtree(build, ignore_errors=True)          # it holds the Wi-Fi password


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--flash", action="store_true", help="also flash over USB (first install)")
    a = ap.parse_args(argv)
    try:
        publish(a.flash)
    except RuntimeError as e:
        print("core2:", e)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
